create or replace function public.convert_won_lead(
  p_organization_id uuid,
  p_lead_id uuid,
  p_project_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_lead public.leads%rowtype;
  v_stage public.pipeline_stages%rowtype;
  v_client_id uuid;
  v_project_id uuid;
  v_existing jsonb;
begin
  if not private.can_write_org(p_organization_id) then raise exception 'Access denied'; end if;
  select * into v_lead from public.leads
    where id = p_lead_id and organization_id = p_organization_id for update;
  if not found then raise exception 'Lead not found'; end if;
  select metadata into v_existing from public.lead_events
  where organization_id = p_organization_id and source = 'user'
    and idempotency_key = 'deal_won:' || v_lead.id::text;
  if found then return v_existing; end if;
  select * into v_stage from public.pipeline_stages where id = v_lead.stage_id;
  if not v_stage.is_won then raise exception 'Lead is not in a won stage'; end if;

  insert into public.clients (
    organization_id, source_lead_id, owner_id, name, company, email, phone, created_by
  ) values (
    p_organization_id, v_lead.id, v_lead.owner_id, v_lead.name,
    v_lead.company, v_lead.email, v_lead.phone, auth.uid()
  ) on conflict (organization_id, source_lead_id) do update set updated_at = now()
  returning id into v_client_id;

  insert into public.projects (
    organization_id, client_id, owner_id, name, status, created_by
  ) values (
    p_organization_id, v_client_id, v_lead.owner_id, trim(p_project_name), 'planned', auth.uid()
  ) returning id into v_project_id;

  insert into public.lead_events (
    organization_id, lead_id, actor_user_id, event_type, metadata, source,
    idempotency_key
  ) values (
    p_organization_id, v_lead.id, auth.uid(), 'deal_won',
    jsonb_build_object('client_id', v_client_id, 'project_id', v_project_id),
    'user', 'deal_won:' || v_lead.id::text
  ) on conflict (organization_id, source, idempotency_key) where idempotency_key is not null do nothing;

  return jsonb_build_object('client_id', v_client_id, 'project_id', v_project_id);
end;
$$;

