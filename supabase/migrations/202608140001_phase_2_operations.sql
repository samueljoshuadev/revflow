create or replace function public.update_meeting_status(
  p_organization_id uuid,
  p_meeting_id uuid,
  p_status text,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_meeting public.meetings%rowtype;
begin
  if not private.can_write_org(p_organization_id) or
     p_status not in ('scheduled', 'cancelled', 'completed', 'no_show') then
    raise exception 'Access denied or invalid status';
  end if;
  select * into v_meeting from public.meetings
  where id = p_meeting_id and organization_id = p_organization_id for update;
  if not found then raise exception 'Meeting not found'; end if;

  update public.meetings set
    status = p_status,
    cancellation_reason = case when p_status = 'cancelled' then nullif(trim(p_reason), '') else cancellation_reason end,
    cancelled_at = case when p_status = 'cancelled' then now() else null end
  where id = v_meeting.id;

  insert into public.lead_events (
    organization_id, lead_id, actor_user_id, event_type, metadata, source
  ) values (
    p_organization_id, v_meeting.lead_id, auth.uid(),
    case p_status when 'cancelled' then 'meeting_cancelled'
                  when 'completed' then 'meeting_completed'
                  when 'no_show' then 'meeting_no_show'
                  else 'meeting_rescheduled' end,
    jsonb_build_object('meeting_id', v_meeting.id, 'reason', nullif(trim(p_reason), '')),
    'user'
  );
end;
$$;

