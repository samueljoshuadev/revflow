create or replace function public.book_public_meeting(
  p_slug text,
  p_name text,
  p_email text,
  p_phone text,
  p_company text,
  p_starts_at timestamptz,
  p_idempotency_key text,
  p_website text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_org public.organizations%rowtype;
  v_owner_id uuid;
  v_pipeline_id uuid;
  v_stage_id uuid;
  v_lead_id uuid;
  v_meeting_id uuid;
  v_ends_at timestamptz;
  v_local_start timestamp;
  v_hours jsonb;
  v_open time;
  v_close time;
  v_email_hash text;
  v_inserted integer;
begin
  if coalesce(p_website, '') <> '' then raise exception 'Invalid request'; end if;
  if char_length(trim(p_name)) not between 2 and 160 or
     char_length(trim(p_email)) > 254 or position('@' in p_email) <= 1 or
     char_length(p_idempotency_key) not between 16 and 200 or
     p_starts_at < now() + interval '30 minutes' or p_starts_at > now() + interval '90 days' then
    raise exception 'Invalid booking data';
  end if;

  select * into v_org from public.organizations
  where slug = p_slug and booking_enabled = true;
  if not found then raise exception 'Booking page not available'; end if;

  v_email_hash := encode(digest(lower(trim(p_email)), 'sha256'), 'hex');
  select meeting_id into v_meeting_id from private.booking_requests
  where organization_id = v_org.id and idempotency_key = p_idempotency_key;
  if found and v_meeting_id is not null then
    return jsonb_build_object('meeting_id', v_meeting_id, 'created', false);
  end if;
  if (select count(*) from private.booking_requests
      where organization_id = v_org.id and email_hash = v_email_hash
        and created_at > now() - interval '1 hour') >= 3 then
    raise exception 'Booking rate limit exceeded';
  end if;

  insert into private.booking_requests (organization_id, idempotency_key, email_hash)
  values (v_org.id, p_idempotency_key, v_email_hash)
  on conflict do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then raise exception 'Booking request already processing'; end if;

  v_ends_at := p_starts_at + make_interval(mins => v_org.booking_duration_minutes);
  v_local_start := p_starts_at at time zone v_org.timezone;
  v_hours := v_org.business_hours -> extract(isodow from v_local_start)::integer::text;
  if v_hours is null or jsonb_array_length(v_hours) <> 2 then raise exception 'Outside business hours'; end if;
  v_open := (v_hours ->> 0)::time;
  v_close := (v_hours ->> 1)::time;
  if v_local_start::time < v_open or
     (v_ends_at at time zone v_org.timezone)::time > v_close then
    raise exception 'Outside business hours';
  end if;

  select user_id into v_owner_id from public.organization_members
  where organization_id = v_org.id and role <> 'viewer'
  order by case role when 'owner' then 0 when 'manager' then 1 when 'member' then 2 else 3 end,
           created_at
  limit 1;
  select id into v_pipeline_id from public.pipelines
  where organization_id = v_org.id and is_default = true;
  select id into v_stage_id from public.pipeline_stages
  where organization_id = v_org.id and pipeline_id = v_pipeline_id
  order by position limit 1;
  if v_owner_id is null or v_stage_id is null then raise exception 'Booking configuration incomplete'; end if;

  perform pg_advisory_xact_lock(hashtextextended(v_org.id::text || v_owner_id::text, 0));
  if exists (select 1 from public.meetings
    where organization_id = v_org.id and owner_id = v_owner_id and status = 'scheduled'
      and starts_at < v_ends_at + make_interval(mins => v_org.booking_buffer_minutes)
      and ends_at + make_interval(mins => v_org.booking_buffer_minutes) > p_starts_at
  ) then raise exception 'Meeting time is no longer available'; end if;

  insert into public.leads (
    organization_id, pipeline_id, stage_id, owner_id, name, email, phone,
    company, source, priority, custom_fields, created_by
  ) values (
    v_org.id, v_pipeline_id, v_stage_id, v_owner_id, trim(p_name), lower(trim(p_email)),
    nullif(trim(p_phone), ''), nullif(trim(p_company), ''), 'public_booking',
    'medium', '{}'::jsonb, null
  ) returning id into v_lead_id;

  insert into public.meetings (
    organization_id, lead_id, owner_id, title, starts_at, ends_at, location,
    timezone, external_provider, external_id, created_by
  ) values (
    v_org.id, v_lead_id, v_owner_id, 'Reunião com ' || trim(p_name),
    p_starts_at, v_ends_at, v_org.meeting_location, v_org.timezone,
    'public_booking', p_idempotency_key, null
  ) returning id into v_meeting_id;

  insert into public.lead_events (
    organization_id, lead_id, actor_user_id, event_type, metadata, source,
    idempotency_key
  ) values (
    v_org.id, v_lead_id, null, 'meeting_scheduled',
    jsonb_build_object('meeting_id', v_meeting_id, 'starts_at', p_starts_at),
    'automation', 'public_booking:' || p_idempotency_key
  );
  update private.booking_requests set meeting_id = v_meeting_id
  where organization_id = v_org.id and idempotency_key = p_idempotency_key;

  return jsonb_build_object('meeting_id', v_meeting_id, 'created', true);
end;
$$;

