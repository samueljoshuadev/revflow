create or replace function public.accept_organization_invitation(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_invitation public.organization_invitations%rowtype;
  v_user_id uuid := auth.uid();
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if v_user_id is null or char_length(p_token) < 32 then
    raise exception 'Invalid invitation';
  end if;

  select * into v_invitation
  from public.organization_invitations
  where token_hash = encode(digest(p_token, 'sha256'), 'hex')
    and accepted_at is null and revoked_at is null and expires_at > now()
  for update;

  if not found or lower(v_invitation.email) <> v_email then
    raise exception 'Invitation not found, expired or assigned to another email';
  end if;

  insert into public.organization_members (organization_id, user_id, role)
  values (v_invitation.organization_id, v_user_id, v_invitation.role)
  on conflict (organization_id, user_id) do nothing;

  update public.organization_invitations set accepted_at = now()
  where id = v_invitation.id;

  return v_invitation.organization_id;
end;
$$;

revoke all on function public.accept_organization_invitation(text) from public;
grant execute on function public.accept_organization_invitation(text) to authenticated;

create or replace function public.update_lead_details(
  p_organization_id uuid,
  p_lead_id uuid,
  p_name text,
  p_email text,
  p_phone text,
  p_company text,
  p_service_id uuid,
  p_owner_id uuid,
  p_source text,
  p_campaign text,
  p_estimated_budget numeric,
  p_priority public.lead_priority,
  p_score smallint,
  p_summary text,
  p_next_action text,
  p_tag_ids uuid[] default '{}'::uuid[]
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not private.can_write_org(p_organization_id) then raise exception 'Access denied'; end if;
  if char_length(trim(p_name)) < 2 or p_score not between 0 and 100 then
    raise exception 'Invalid lead data';
  end if;
  if p_service_id is not null and not exists (
    select 1 from public.services where id = p_service_id and organization_id = p_organization_id
  ) then raise exception 'Invalid service'; end if;
  if p_owner_id is not null and not exists (
    select 1 from public.organization_members where user_id = p_owner_id and organization_id = p_organization_id
  ) then raise exception 'Invalid owner'; end if;
  if exists (
    select 1 from unnest(p_tag_ids) tag_id
    where not exists (select 1 from public.tags where id = tag_id and organization_id = p_organization_id)
  ) then raise exception 'Invalid tag'; end if;

  update public.leads set
    name = trim(p_name), email = nullif(trim(p_email), ''), phone = nullif(trim(p_phone), ''),
    company = nullif(trim(p_company), ''), service_id = p_service_id, owner_id = p_owner_id,
    source = nullif(trim(p_source), ''), campaign = nullif(trim(p_campaign), ''),
    estimated_budget = p_estimated_budget, priority = p_priority, score = p_score,
    summary = nullif(trim(p_summary), ''), next_action = nullif(trim(p_next_action), ''),
    last_interaction_at = now()
  where id = p_lead_id and organization_id = p_organization_id;
  if not found then raise exception 'Lead not found'; end if;

  delete from public.lead_tags where lead_id = p_lead_id and organization_id = p_organization_id;
  insert into public.lead_tags (organization_id, lead_id, tag_id)
  select p_organization_id, p_lead_id, tag_id from unnest(p_tag_ids) tag_id;

  insert into public.lead_events (organization_id, lead_id, actor_user_id, event_type, metadata, source)
  values (p_organization_id, p_lead_id, auth.uid(), 'lead_updated',
    jsonb_build_object('owner_id', p_owner_id, 'priority', p_priority, 'score', p_score), 'user');
end;
$$;

