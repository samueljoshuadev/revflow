create or replace function public.schedule_meeting(
  p_organization_id uuid,
  p_lead_id uuid,
  p_owner_id uuid,
  p_title text,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_timezone text,
  p_description text default null,
  p_location text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_meeting_id uuid;
begin
  if not private.can_write_org(p_organization_id) then
    raise exception 'Access denied';
  end if;
  if p_ends_at <= p_starts_at or p_starts_at < now() - interval '5 minutes' then
    raise exception 'Invalid meeting period';
  end if;
  if not exists (select 1 from public.leads where id = p_lead_id and organization_id = p_organization_id) or
     not exists (select 1 from public.organization_members where organization_id = p_organization_id and user_id = p_owner_id) then
    raise exception 'Lead or owner does not belong to the organization';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_organization_id::text || p_owner_id::text, 0));
  if exists (
    select 1 from public.meetings
    where organization_id = p_organization_id and owner_id = p_owner_id
      and status = 'scheduled' and starts_at < p_ends_at and ends_at > p_starts_at
  ) then
    raise exception 'Meeting time conflicts with another appointment';
  end if;

  insert into public.meetings (
    organization_id, lead_id, owner_id, title, starts_at, ends_at,
    timezone, description, location, created_by
  ) values (
    p_organization_id, p_lead_id, p_owner_id, trim(p_title), p_starts_at,
    p_ends_at, p_timezone, nullif(trim(p_description), ''),
    nullif(trim(p_location), ''), auth.uid()
  ) returning id into v_meeting_id;

  insert into public.lead_events (
    organization_id, lead_id, actor_user_id, event_type, metadata, source
  ) values (
    p_organization_id, p_lead_id, auth.uid(), 'meeting_scheduled',
    jsonb_build_object('meeting_id', v_meeting_id, 'starts_at', p_starts_at), 'user'
  );

  return v_meeting_id;
end;
$$;

