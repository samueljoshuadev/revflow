create or replace function public.get_operational_metrics(p_organization_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select case when private.is_org_member(p_organization_id) then jsonb_build_object(
    'upcoming_meetings', (select count(*) from public.meetings where organization_id = p_organization_id and status = 'scheduled' and starts_at between now() and now() + interval '7 days'),
    'open_tasks', (select count(*) from public.tasks where organization_id = p_organization_id and status in ('pending', 'in_progress')),
    'overdue_tasks', (select count(*) from public.tasks where organization_id = p_organization_id and status in ('pending', 'in_progress') and due_at < now()),
    'active_clients', (select count(*) from public.clients where organization_id = p_organization_id and status = 'active'),
    'active_projects', (select count(*) from public.projects where organization_id = p_organization_id and status in ('planned', 'active', 'paused')),
    'seller_performance', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', om.user_id,
        'name', coalesce(pr.full_name, 'Membro'),
        'leads', coalesce(t.leads, 0),
        'won', coalesce(t.won, 0),
        'pipeline_value', coalesce(t.pipeline_value, 0)
      ) order by coalesce(t.won, 0) desc, coalesce(t.pipeline_value, 0) desc)
      from public.organization_members om
      left join public.profiles pr on pr.id = om.user_id
      left join (
        select l.owner_id, count(*) leads,
          count(*) filter (where ps.is_won) won,
          coalesce(sum(l.estimated_budget) filter (where not ps.is_closed), 0) pipeline_value
        from public.leads l join public.pipeline_stages ps on ps.id = l.stage_id
        where l.organization_id = p_organization_id and l.archived_at is null
        group by l.owner_id
      ) t on t.owner_id = om.user_id
      where om.organization_id = p_organization_id
    ), '[]'::jsonb)
  ) else null end;
$$;

