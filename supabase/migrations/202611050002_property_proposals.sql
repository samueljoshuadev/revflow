create or replace function private.record_proposal_event(
  p_proposal public.property_proposals,
  p_event_type text,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_metadata jsonb := jsonb_build_object(
    'proposal_id', p_proposal.id,
    'number', p_proposal.number,
    'unit_id', p_proposal.unit_id,
    'status', p_proposal.status
  ) || coalesce(p_metadata, '{}'::jsonb);
begin
  insert into public.real_estate_events (
    organization_id, entity_type, entity_id, actor_user_id, event_type, metadata
  ) values (
    p_proposal.organization_id, 'proposal', p_proposal.id, auth.uid(), p_event_type, v_metadata
  );
  if p_proposal.lead_id is not null then
    insert into public.lead_events (
      organization_id, lead_id, actor_user_id, event_type, metadata, source
    ) values (
      p_proposal.organization_id, p_proposal.lead_id, auth.uid(), p_event_type, v_metadata,
      case when auth.uid() is null then 'system' else 'user' end::public.event_source
    );
  end if;
end;
$$;

