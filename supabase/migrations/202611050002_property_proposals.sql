create or replace function public.submit_property_proposal(
  p_organization_id uuid,
  p_proposal_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_proposal public.property_proposals%rowtype;
  v_unit public.development_units%rowtype;
  v_missing text[];
  v_sla smallint;
  v_position integer;
  v_resubmission boolean;
begin
  if not private.can_edit_proposal(p_proposal_id) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;

  select * into v_proposal from public.property_proposals
  where id = p_proposal_id and organization_id = p_organization_id;
  if not found then
    raise exception 'proposal_not_found' using errcode = 'P0002';
  end if;

  -- Serializa a fila da unidade.
  select * into v_unit from public.development_units
  where id = v_proposal.unit_id and organization_id = p_organization_id
  for update;

  select * into v_proposal from public.property_proposals
  where id = p_proposal_id for update;
  if v_proposal.status not in ('draft', 'countered') then
    raise exception 'invalid_status' using errcode = 'P0001';
  end if;

  v_missing := public.get_proposal_missing_requirements(p_proposal_id);
  if cardinality(v_missing) > 0 then
    return jsonb_build_object('status', v_proposal.status, 'missing', to_jsonb(v_missing));
  end if;

  select proposal_sla_hours into v_sla from public.organizations where id = p_organization_id;
  v_resubmission := v_proposal.status = 'countered';

  if v_resubmission then
    update public.property_proposals
    set status = 'in_review',
        sla_due_at = now() + make_interval(hours => v_sla),
        sla_breach_notified_at = null,
        decided_at = null,
        decided_by = null
    where id = p_proposal_id
    returning * into v_proposal;
  elsif v_unit.status = 'available' then
    update public.property_proposals
    set status = 'in_review',
        submitted_at = now(),
        sla_due_at = now() + make_interval(hours => v_sla)
    where id = p_proposal_id
    returning * into v_proposal;
    update public.development_units set status = 'in_proposal' where id = v_unit.id;
  elsif v_unit.status = 'in_proposal' then
    select coalesce(max(queue_position), 0) + 1 into v_position
    from public.property_proposals
    where unit_id = v_unit.id and status = 'queued';
    update public.property_proposals
    set status = 'queued',
        queue_position = v_position,
        submitted_at = now()
    where id = p_proposal_id
    returning * into v_proposal;
  else
    raise exception 'unit_unavailable' using errcode = 'P0001';
  end if;

  if v_proposal.status = 'queued' then
    perform private.record_proposal_event(v_proposal, 'proposal_queued',
      jsonb_build_object('queue_position', v_proposal.queue_position));
  else
    perform private.record_proposal_event(v_proposal,
      case when v_resubmission then 'proposal_resubmitted' else 'proposal_submitted' end);
    perform private.notify_proposal_admins(
      v_proposal, 'proposal_submitted', 'Nova proposta em análise',
      private.proposal_label(v_proposal) || ' aguarda aprovação.'
    );
  end if;

  if v_proposal.lead_id is not null and not v_resubmission then
    perform private.apply_kanban_automation(
      p_organization_id, v_proposal.lead_id, 'proposal_sent',
      'property_proposal_sent:' || v_proposal.id::text
    );
  end if;

  return jsonb_build_object(
    'status', v_proposal.status,
    'queue_position', v_proposal.queue_position,
    'missing', '[]'::jsonb
  );
end;
$$;

create or replace function public.decide_property_proposal(
  p_organization_id uuid,
  p_proposal_id uuid,
  p_decision text,
  p_note text default null,
  p_counter_offer_price numeric default null
)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_proposal public.property_proposals%rowtype;
  v_other public.property_proposals%rowtype;
  v_sla smallint;
begin
  if not private.is_org_admin(p_organization_id) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;
  if p_decision not in ('approved', 'rejected', 'countered') then
    raise exception 'invalid_decision' using errcode = '22023';
  end if;
  if p_decision = 'countered' and (p_counter_offer_price is null or p_counter_offer_price <= 0) then
    raise exception 'counter_price_required' using errcode = '22023';
  end if;

  select * into v_proposal from public.property_proposals
  where id = p_proposal_id and organization_id = p_organization_id;
  if not found then
    raise exception 'proposal_not_found' using errcode = 'P0002';
  end if;
  perform 1 from public.development_units where id = v_proposal.unit_id for update;
  select * into v_proposal from public.property_proposals where id = p_proposal_id for update;

  if not (
    v_proposal.status = 'in_review'
    or (v_proposal.status = 'countered' and p_decision = 'rejected')
  ) then
    raise exception 'invalid_status' using errcode = 'P0001';
  end if;

  select proposal_sla_hours into v_sla from public.organizations where id = p_organization_id;

  update public.property_proposals
  set status = p_decision,
      decided_at = now(),
      decided_by = auth.uid(),
      decision_note = nullif(btrim(p_note), ''),
      counter_offer_price = case when p_decision = 'countered' then p_counter_offer_price else counter_offer_price end,
      sla_due_at = case when p_decision = 'countered' then now() + make_interval(hours => v_sla) else sla_due_at end,
      sla_breach_notified_at = null
  where id = p_proposal_id
  returning * into v_proposal;

  perform private.record_proposal_event(v_proposal, 'proposal_' || p_decision,
    case when p_decision = 'countered'
      then jsonb_build_object('counter_offer_price', p_counter_offer_price)
      else '{}'::jsonb end);

  if p_decision = 'approved' then
    update public.development_units set status = 'reserved' where id = v_proposal.unit_id;
    for v_other in
      update public.property_proposals
      set status = 'rejected',
          queue_position = null,
          decided_at = now(),
          decided_by = auth.uid(),
          decision_note = 'Unidade reservada para outra proposta.'
      where unit_id = v_proposal.unit_id and status = 'queued'
      returning *
    loop
      perform private.record_proposal_event(v_other, 'proposal_rejected',
        jsonb_build_object('reason', 'unit_reserved'));
      perform private.notify_proposal_team(
        v_other, 'proposal_rejected', 'Proposta encerrada',
        private.proposal_label(v_other) || ': a unidade foi reservada para outra proposta.'
      );
    end loop;
    perform private.notify_proposal_team(
      v_proposal, 'proposal_approved', 'Proposta aprovada',
      private.proposal_label(v_proposal) || ' foi aprovada.'
    );
    if v_proposal.lead_id is not null then
      perform private.apply_kanban_automation(
        p_organization_id, v_proposal.lead_id, 'proposal_accepted',
        'property_proposal_accepted:' || v_proposal.id::text
      );
    end if;
  elsif p_decision = 'rejected' then
    perform private.notify_proposal_team(
      v_proposal, 'proposal_rejected', 'Proposta recusada',
      private.proposal_label(v_proposal) || ' foi recusada.'
    );
    perform private.release_unit_lock(p_organization_id, v_proposal.unit_id);
    if v_proposal.lead_id is not null then
      perform private.apply_kanban_automation(
        p_organization_id, v_proposal.lead_id, 'proposal_rejected',
        'property_proposal_rejected:' || v_proposal.id::text
      );
    end if;
  else
    perform private.notify_proposal_team(
      v_proposal, 'proposal_countered', 'Contraproposta recebida',
      private.proposal_label(v_proposal) || ': a incorporadora enviou uma contraproposta.'
    );
  end if;

  return v_proposal.status;
end;
$$;

create or replace function public.cancel_property_proposal(
  p_organization_id uuid,
  p_proposal_id uuid,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_proposal public.property_proposals%rowtype;
  v_held_lock boolean;
begin
  select * into v_proposal from public.property_proposals
  where id = p_proposal_id and organization_id = p_organization_id;
  if not found or not private.can_write_org(p_organization_id) or not (
    private.is_org_admin(p_organization_id)
    or auth.uid() in (v_proposal.broker_user_id, v_proposal.created_by)
  ) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;

  perform 1 from public.development_units where id = v_proposal.unit_id for update;
  select * into v_proposal from public.property_proposals where id = p_proposal_id for update;
  if v_proposal.status not in ('draft', 'queued', 'in_review', 'countered') then
    raise exception 'invalid_status' using errcode = 'P0001';
  end if;
  v_held_lock := v_proposal.status in ('in_review', 'countered');

  update public.property_proposals
  set status = 'cancelled',
      queue_position = null,
      cancelled_at = now(),
      cancel_reason = nullif(btrim(p_reason), '')
  where id = p_proposal_id
  returning * into v_proposal;

  perform private.record_proposal_event(v_proposal, 'proposal_cancelled');
  if v_held_lock then
    perform private.release_unit_lock(p_organization_id, v_proposal.unit_id);
  end if;
end;
$$;

/** Executado pelo cron com service role. */
create or replace function public.process_proposal_deadlines(p_limit integer default 100)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_proposal public.property_proposals%rowtype;
  v_expired integer := 0;
  v_breached integer := 0;
  v_limit integer := least(greatest(coalesce(p_limit, 100), 1), 500);
begin
  -- Contraproposta sem resposta do corretor no prazo: expira e libera a unidade.
  for v_proposal in
    select * from public.property_proposals
    where status = 'countered' and sla_due_at < now()
    order by sla_due_at
    limit v_limit
    for update skip locked
  loop
    perform 1 from public.development_units where id = v_proposal.unit_id for update;
    update public.property_proposals set status = 'expired'
    where id = v_proposal.id and status = 'countered'
    returning * into v_proposal;
    if found then
      perform private.record_proposal_event(v_proposal, 'proposal_expired');
      perform private.notify_proposal_team(
        v_proposal, 'proposal_expired', 'Contraproposta expirada',
        private.proposal_label(v_proposal) || ' expirou sem resposta e a unidade foi liberada.'
      );
      perform private.release_unit_lock(v_proposal.organization_id, v_proposal.unit_id);
      v_expired := v_expired + 1;
    end if;
  end loop;

  -- Proposta em análise além do prazo: avisa uma vez (admins e equipe).
  for v_proposal in
    update public.property_proposals
    set sla_breach_notified_at = now()
    where id in (
      select id from public.property_proposals
      where status = 'in_review' and sla_due_at < now() and sla_breach_notified_at is null
      order by sla_due_at
      limit v_limit
      for update skip locked
    )
    returning *
  loop
    perform private.record_proposal_event(v_proposal, 'proposal_sla_breached');
    perform private.notify_proposal_admins(
      v_proposal, 'proposal_sla_breached', 'Prazo de aprovação vencido',
      private.proposal_label(v_proposal) || ' passou do prazo de análise.'
    );
    perform private.notify_proposal_team(
      v_proposal, 'proposal_sla_breached', 'Proposta sem retorno no prazo',
      private.proposal_label(v_proposal) || ' ainda aguarda a incorporadora.'
    );
    v_breached := v_breached + 1;
  end loop;

  return jsonb_build_object('expired', v_expired, 'sla_breached', v_breached);
end;
$$;

