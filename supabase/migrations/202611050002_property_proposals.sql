create or replace function public.create_property_proposal(
  p_organization_id uuid,
  p_unit_id uuid,
  p_offered_price numeric,
  p_down_payment numeric,
  p_fgts_amount numeric,
  p_financing_amount numeric,
  p_payment_notes text,
  p_buyer_name text,
  p_buyer_phone text,
  p_buyer_email text,
  p_lead_id uuid default null,
  p_partner_agency_id uuid default null,
  p_external_broker_name text default null,
  p_external_broker_phone text default null,
  p_external_broker_creci text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_unit public.development_units%rowtype;
  v_manager uuid;
  v_director uuid;
  v_proposal public.property_proposals%rowtype;
begin
  if auth.uid() is null or not private.can_write_org(p_organization_id) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;

  select * into v_unit from public.development_units
  where id = p_unit_id and organization_id = p_organization_id;
  if not found then
    raise exception 'unit_not_found' using errcode = 'P0002';
  end if;
  if v_unit.status not in ('available', 'in_proposal') then
    raise exception 'unit_unavailable' using errcode = 'P0001';
  end if;
  if exists (
    select 1 from public.developments
    where id = v_unit.development_id and archived_at is not null
  ) then
    raise exception 'unit_unavailable' using errcode = 'P0001';
  end if;

  if p_lead_id is not null and not exists (
    select 1 from public.leads where id = p_lead_id and organization_id = p_organization_id
  ) then
    raise exception 'lead_not_found' using errcode = 'P0002';
  end if;
  if p_partner_agency_id is not null and not exists (
    select 1 from public.partner_agencies
    where id = p_partner_agency_id and organization_id = p_organization_id and archived_at is null
  ) then
    raise exception 'partner_not_found' using errcode = 'P0002';
  end if;

  select reports_to_user_id into v_manager from public.organization_members
  where organization_id = p_organization_id and user_id = auth.uid();
  if v_manager is not null then
    select reports_to_user_id into v_director from public.organization_members
    where organization_id = p_organization_id and user_id = v_manager;
  end if;

