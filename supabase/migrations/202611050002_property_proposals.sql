create or replace function public.set_member_reports_to(
  p_organization_id uuid,
  p_user_id uuid,
  p_reports_to_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_cursor uuid := p_reports_to_user_id;
  v_depth integer := 0;
begin
  if not private.is_org_admin(p_organization_id) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;
  if p_reports_to_user_id = p_user_id then
    raise exception 'invalid_hierarchy' using errcode = '22023';
  end if;
  -- Impede ciclos (A → B → A).
  while v_cursor is not null and v_depth < 20 loop
    if v_cursor = p_user_id then
      raise exception 'invalid_hierarchy' using errcode = '22023';
    end if;
    select reports_to_user_id into v_cursor from public.organization_members
    where organization_id = p_organization_id and user_id = v_cursor;
    v_depth := v_depth + 1;
  end loop;

  update public.organization_members
  set reports_to_user_id = p_reports_to_user_id
  where organization_id = p_organization_id and user_id = p_user_id;
  if not found then
    raise exception 'member_not_found' using errcode = 'P0002';
  end if;
end;
$$;

