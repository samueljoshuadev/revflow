create or replace function private.can_view_proposal(p_proposal_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.property_proposals p
    where p.id = p_proposal_id
      and private.is_org_member(p.organization_id)
      and (
        private.is_org_admin(p.organization_id)
        or auth.uid() in (p.broker_user_id, p.manager_user_id, p.director_user_id, p.created_by)
      )
  );
$$;

create or replace function private.can_edit_proposal(p_proposal_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.property_proposals p
    where p.id = p_proposal_id
      and p.status in ('draft', 'countered')
      and private.can_write_org(p.organization_id)
      and (
        private.is_org_admin(p.organization_id)
        or auth.uid() in (p.broker_user_id, p.created_by)
      )
  );
$$;

