    payment_notes, created_by
  ) values (
    p_organization_id, p_unit_id, p_lead_id, auth.uid(), v_manager,
    case when v_director = auth.uid() then null else v_director end,
    p_partner_agency_id, nullif(btrim(p_external_broker_name), ''),
    nullif(btrim(p_external_broker_phone), ''), nullif(btrim(p_external_broker_creci), ''),
