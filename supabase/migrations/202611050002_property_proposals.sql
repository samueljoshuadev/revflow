-- Propostas por unidade do espelho: compradores, documentos, fila e aprovação.
--
-- Regras de negócio:
-- * A primeira proposta enviada trava a unidade (in_review). As seguintes entram
--   na fila (queued) e sobem sozinhas quando a ativa é recusada, cancelada ou expira.
-- * Somente owner/admin veem todas as propostas e decidem. O corretor vê as suas;
--   gerente e diretor veem as que foram vinculadas a eles pela hierarquia.
-- * Prazo (proposal_sla_hours, padrão 48h): proposta em análise vencida gera aviso;
--   contraproposta sem resposta do corretor no prazo expira e libera a unidade.

-- ---------------------------------------------------------------------------
-- Configuração e hierarquia
-- ---------------------------------------------------------------------------

alter table public.organizations
  add column if not exists proposal_sla_hours smallint not null default 48
    check (proposal_sla_hours between 1 and 720);

alter table public.organization_members
  add column if not exists reports_to_user_id uuid;

alter table public.organization_members
  drop constraint if exists organization_members_reports_to_fk;
alter table public.organization_members
  add constraint organization_members_reports_to_fk
    foreign key (organization_id, reports_to_user_id)
    references public.organization_members(organization_id, user_id)
    on delete set null (reports_to_user_id);
alter table public.organization_members
  drop constraint if exists organization_members_reports_to_self_check;
alter table public.organization_members
  add constraint organization_members_reports_to_self_check
    check (reports_to_user_id is null or reports_to_user_id <> user_id);

alter table public.notifications
  add column if not exists action_path text
    check (action_path is null or action_path ~ '^/[A-Za-z0-9/_-]{0,200}$');

