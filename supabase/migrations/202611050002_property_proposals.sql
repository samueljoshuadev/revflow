/** Avisa corretor e gerente (e diretor) de uma mudança na proposta. */
create or replace function private.notify_proposal_team(
  p_proposal public.property_proposals,
  p_kind text,
  p_title text,
  p_body text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid;
  v_path text := '/proposals/' || p_proposal.id::text;
begin
  foreach v_user in array array[
    p_proposal.broker_user_id, p_proposal.manager_user_id, p_proposal.director_user_id
  ] loop
    if v_user is not null and v_user is distinct from auth.uid() then
      perform private.notify_member(
        p_proposal.organization_id, v_user, p_kind, p_title, p_body,
        p_kind || ':' || p_proposal.id::text || ':' || coalesce(p_proposal.decided_at, p_proposal.updated_at)::text,
        v_path
      );
    end if;
  end loop;
end;
$$;

create or replace function private.notify_proposal_admins(
  p_proposal public.property_proposals,
  p_kind text,
  p_title text,
  p_body text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid;
begin
  for v_user in
    select user_id from public.organization_members
    where organization_id = p_proposal.organization_id and role in ('owner', 'admin')
    limit 50
  loop
    if v_user is distinct from auth.uid() then
      perform private.notify_member(
        p_proposal.organization_id, v_user, p_kind, p_title, p_body,
        p_kind || ':' || p_proposal.id::text || ':' || coalesce(p_proposal.submitted_at, p_proposal.updated_at)::text,
        '/proposals/' || p_proposal.id::text
      );
    end if;
  end loop;
end;
$$;

