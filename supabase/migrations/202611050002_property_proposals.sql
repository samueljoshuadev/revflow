    coalesce(p_financing_amount, 0), nullif(btrim(p_payment_notes), ''), auth.uid()
  )
  returning * into v_proposal;

  insert into public.proposal_parties (
    organization_id, proposal_id, role, full_name, phone, email
  ) values (
    p_organization_id, v_proposal.id, 'buyer', btrim(p_buyer_name),
    nullif(btrim(p_buyer_phone), ''), nullif(lower(btrim(p_buyer_email)), '')
